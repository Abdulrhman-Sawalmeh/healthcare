def set_rtl(paragraph):
    paragraph.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    p_pr = paragraph._p.get_or_add_pPr()
    bidi = p_pr.find(qn("w:bidi"))
    if bidi is None:
        bidi = OxmlElement("w:bidi")
        p_pr.append(bidi)
    bidi.set(qn("w:val"), "1")


def set_run_font(run, size=None, bold=None):
    run.font.name = "Arial"
    run._element.rPr.rFonts.set(qn("w:ascii"), "Arial")
    run._element.rPr.rFonts.set(qn("w:hAnsi"), "Arial")
    run._element.rPr.rFonts.set(qn("w:cs"), "Arial")
    rtl = run._element.rPr.find(qn("w:rtl"))
    if rtl is None:
        rtl = OxmlElement("w:rtl")
        run._element.rPr.append(rtl)
    rtl.set(qn("w:val"), "1")
    if size:
        run.font.size = Pt(size)
    if bold is not None:
        run.bold = bold


def add_paragraph(doc, text="", style=None, size=11, bold=False):
    paragraph = doc.add_paragraph(style=style)
    set_rtl(paragraph)
    run = paragraph.add_run(text)
    set_run_font(run, size=size, bold=bold)
    return paragraph


def add_heading(doc, text, level=1):
    paragraph = doc.add_heading(level=level)
    set_rtl(paragraph)
    run = paragraph.add_run(text)
    set_run_font(run, size={1: 18, 2: 15, 3: 13}.get(level, 12), bold=True)
    return paragraph


def add_bullets(doc, items, level=0):
    for item in items:
        paragraph = doc.add_paragraph(style="List Bullet" if level == 0 else "List Bullet 2")
        set_rtl(paragraph)
        run = paragraph.add_run(item)
        set_run_font(run, size=10.5)


def add_numbered(doc, items):
    for item in items:
        paragraph = doc.add_paragraph(style="List Number")
        set_rtl(paragraph)
        run = paragraph.add_run(item)
        set_run_font(run, size=10.5)


def add_image(doc, file_name, caption):
    image_path = SCREENSHOTS_DIR / f"{file_name}.png"
    if not image_path.exists():
        add_paragraph(doc, f"الصورة غير متوفرة: {file_name}", size=10, bold=True)
        return

    paragraph = doc.add_paragraph()
    paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = paragraph.add_run()
    run.add_picture(str(image_path), width=Inches(6.7))
    add_paragraph(doc, caption, size=9, bold=True)


def add_page_section(doc, title, screenshot, purpose, content, controls, notes=None):
    add_heading(doc, title, 3)
    add_paragraph(doc, f"الغرض من الواجهة: {purpose}", size=10.5, bold=True)
    add_paragraph(doc, "ما تحتويه الواجهة:", size=10.5, bold=True)
    add_bullets(doc, content)
    add_paragraph(doc, "الأزرار والحقول وما تقوم به:", size=10.5, bold=True)
    add_bullets(doc, controls)
    if notes:
        add_paragraph(doc, "ملاحظات تشغيلية:", size=10.5, bold=True)
        add_bullets(doc, notes)
    add_image(doc, screenshot, f"صورة واجهة: {title}")


